/*
  Банк питань за моделлю OSI.

  Хибні варіанти — сусідні рівні, а не випадкові: плутають саме канальний із
  мережевим і сеансовий із поданням, тренувати треба це.
*/
NL.mount("Модель OSI");

const L = {
  1: "1 — фізичний", 2: "2 — канальний", 3: "3 — мережевий", 4: "4 — транспортний",
  5: "5 — сеансовий", 6: "6 — подання", 7: "7 — прикладний",
};
const near = n => [L[n - 1], L[n + 1], L[n + 2] || L[n - 2], L[n - 3] || L[7]].filter(Boolean).filter(x => x !== L[n]);

const items = [
  [3, "IP", "Адресація між мережами й маршрутизація — мережевий рівень."],
  [2, "Ethernet", "MAC-адреси та кадри — канальний рівень."],
  [4, "TCP", "Сегменти, порти, гарантія доставки — транспортний рівень."],
  [4, "UDP", "Теж транспортний, але без встановлення з'єднання."],
  [7, "HTTP", "Прикладний: ним користується сам застосунок."],
  [7, "DNS", "Прикладний рівень, хоча ходить поверх UDP/TCP."],
  [1, "Кручена пара", "Середовище передавання й біти — фізичний рівень."],
  [2, "Комутатор", "Працює з MAC-адресами, отже канальний."],
  [3, "Маршрутизатор", "Дивиться на IP-адресу призначення — мережевий."],
  [1, "Повторювач", "Підсилює сигнал, нічого не розбирає — фізичний."],
  [6, "Шифрування й кодування", "Подання даних — шостий рівень."],
  [5, "Встановлення й розрив сеансу", "Сеансовий рівень відповідає за діалог."],
  [2, "ARP", "Шукає MAC за IP, живе на межі канального рівня."],
  [3, "ICMP", "Службові повідомлення мережевого рівня, ним працює ping."],
  [4, "Порт 443", "Номер порту — це транспортний рівень."],
  [2, "Кадр (frame)", "Одиниця даних канального рівня."],
  [3, "Пакет (packet)", "Одиниця даних мережевого рівня."],
  [4, "Сегмент (segment)", "Одиниця даних транспортного рівня."],
  [1, "Біт", "Одиниця даних фізичного рівня."],
];

const questions = items.map(([lvl, thing, why]) => ({
  q: "На якому рівні моделі OSI це працює?",
  given: thing,
  a: L[lvl],
  wrong: near(lvl),
  why,
}));

// Зворотні питання: за рівнем назвати, що на ньому живе — заразом перевіряє,
// що рівень вивчено не як рядок у списку.
const reverse = [
  { q: "Що з цього належить до канального рівня?", a: "MAC-адреса", wrong: ["IP-адреса", "Номер порту", "Доменне ім'я"], why: "MAC — адреса мережевої картки, другий рівень." },
  { q: "Що з цього належить до транспортного рівня?", a: "Номер порту", wrong: ["MAC-адреса", "IP-адреса", "Кадр"], why: "Порт розрізняє застосунки на одному хості." },
  { q: "Скільки рівнів у моделі OSI?", a: "7", wrong: ["4", "5", "6"], why: "Сім. У моделі TCP/IP — чотири." },
  { q: "Скільки рівнів у моделі TCP/IP?", a: "4", wrong: ["3", "5", "7"], why: "Канальний, мережевий, транспортний, прикладний." },
  { q: "Якого рівня OSI немає в моделі TCP/IP окремо?", a: "Сеансового", wrong: ["Мережевого", "Транспортного", "Канального"], why: "Сеансовий і подання входять до прикладного рівня TCP/IP." },
];

Quiz.run({ questions: questions.concat(reverse), kind: "osi", title: "Модель OSI" });
