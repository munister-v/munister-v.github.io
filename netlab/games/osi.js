/*
  Банк вопросов по модели OSI.

  Неправильные варианты — соседние уровни, а не случайные: путают именно
  канальный с сетевым и сеансовый с представлением, и тренировать надо это.
*/
NL.mount("Модель OSI");

const L = {
  1: "1 — физический", 2: "2 — канальный", 3: "3 — сетевой", 4: "4 — транспортный",
  5: "5 — сеансовый", 6: "6 — представления", 7: "7 — прикладной",
};
const near = n => [L[n - 1], L[n + 1], L[n + 2] || L[n - 2], L[n - 3] || L[7]].filter(Boolean).filter(x => x !== L[n]);

const items = [
  [3, "IP", "Адресация между сетями и маршрутизация — сетевой уровень."],
  [2, "Ethernet", "MAC-адреса и кадры — канальный уровень."],
  [4, "TCP", "Сегменты, порты, гарантия доставки — транспортный уровень."],
  [4, "UDP", "Тоже транспортный, но без установления соединения."],
  [7, "HTTP", "Прикладной: им пользуется само приложение."],
  [7, "DNS", "Прикладной уровень, хотя ходит поверх UDP/TCP."],
  [1, "Витая пара", "Среда передачи и биты — физический уровень."],
  [2, "Коммутатор", "Работает с MAC-адресами, значит канальный."],
  [3, "Маршрутизатор", "Смотрит IP-адрес назначения — сетевой."],
  [1, "Повторитель", "Усиливает сигнал, ничего не разбирает — физический."],
  [6, "Шифрование и кодировка", "Представление данных — шестой уровень."],
  [5, "Установление и разрыв сеанса", "Сеансовый уровень отвечает за диалог."],
  [2, "ARP", "Ищет MAC по IP, живёт на границе канального уровня."],
  [3, "ICMP", "Служебные сообщения сетевого уровня, им работает ping."],
  [4, "Порт 443", "Номер порта — это транспортный уровень."],
  [2, "Кадр (frame)", "Единица данных канального уровня."],
  [3, "Пакет (packet)", "Единица данных сетевого уровня."],
  [4, "Сегмент (segment)", "Единица данных транспортного уровня."],
  [1, "Бит", "Единица данных физического уровня."],
];

const questions = items.map(([lvl, thing, why]) => ({
  q: "На каком уровне модели OSI это работает?",
  given: thing,
  a: L[lvl],
  wrong: near(lvl),
  why,
}));

// Обратные вопросы: по уровню назвать, что на нём живёт — заодно проверяет,
// что уровень выучен не как строчка в списке.
const reverse = [
  { q: "Что из этого относится к канальному уровню?", a: "MAC-адрес", wrong: ["IP-адрес", "Номер порта", "Доменное имя"], why: "MAC — адрес сетевой карты, второй уровень." },
  { q: "Что из этого относится к транспортному уровню?", a: "Номер порта", wrong: ["MAC-адрес", "IP-адрес", "Кадр"], why: "Порт различает приложения на одном хосте." },
  { q: "Сколько уровней в модели OSI?", a: "7", wrong: ["4", "5", "6"], why: "Семь. В модели TCP/IP — четыре." },
  { q: "Сколько уровней в модели TCP/IP?", a: "4", wrong: ["3", "5", "7"], why: "Канальный, сетевой, транспортный, прикладной." },
  { q: "Какой уровень OSI отсутствует в модели TCP/IP как отдельный?", a: "Сеансовый", wrong: ["Сетевой", "Транспортный", "Канальный"], why: "Сеансовый и представления входят в прикладной уровень TCP/IP." },
];

Quiz.run({ questions: questions.concat(reverse), kind: "osi", title: "Модель OSI" });
