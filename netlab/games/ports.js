/*
  Порти й протоколи.

  Питаємо в обидва боки: номер за назвою і назву за номером. Хибні варіанти —
  сусідні за змістом служби (SSH/Telnet, HTTP/HTTPS), бо плутають саме їх.
*/
NL.mount("Порти і протоколи");

const P = [
  ["FTP (дані)", 20, "TCP", "Канал даних FTP. Керувальний — 21."],
  ["FTP (керування)", 21, "TCP", "Команди FTP ідуть на 21, дані — на 20."],
  ["SSH", 22, "TCP", "Захищена консоль. Telnet — 23, але він відкритим текстом."],
  ["Telnet", 23, "TCP", "Відкритий текст, у продакшені не використовується."],
  ["SMTP", 25, "TCP", "Надсилання пошти. Приймання — POP3 (110) або IMAP (143)."],
  ["DNS", 53, "UDP/TCP", "Запити по UDP, зонні передачі по TCP."],
  ["DHCP (сервер)", 67, "UDP", "Сервер слухає 67, клієнт відповідає з 68."],
  ["TFTP", 69, "UDP", "Простий обмін файлами без авторизації, часто для образів IOS."],
  ["HTTP", 80, "TCP", "Відкритий веб. Зашифрований — 443."],
  ["POP3", 110, "TCP", "Забирає пошту з видаленням із сервера."],
  ["NTP", 123, "UDP", "Синхронізація часу."],
  ["IMAP", 143, "TCP", "Пошта лишається на сервері, на відміну від POP3."],
  ["SNMP", 161, "UDP", "Опитування пристроїв. Пастки приходять на 162."],
  ["LDAP", 389, "TCP", "Каталог користувачів. Захищений — 636."],
  ["HTTPS", 443, "TCP", "HTTP поверх TLS."],
  ["SMB", 445, "TCP", "Спільні теки Windows."],
  ["RDP", 3389, "TCP", "Віддалений робочий стіл Windows."],
  ["MySQL", 3306, "TCP", "База даних MySQL/MariaDB."],
  ["PostgreSQL", 5432, "TCP", "База даних PostgreSQL."],
];

const nums = P.map(p => p[1]);
const names = P.map(p => p[0]);
const otherNums = n => NL.shuffle(nums.filter(x => x !== n)).slice(0, 3).map(String);
const otherNames = s => NL.shuffle(names.filter(x => x !== s)).slice(0, 3);

const questions = [];
for (const [name, port, proto, why] of P) {
  questions.push({ q: "Який порт у цієї служби?", given: name, a: String(port), wrong: otherNums(port), why });
  questions.push({ q: "Яка служба слухає цей порт?", given: String(port), a: name, wrong: otherNames(name), why });
}

questions.push(
  { q: "Який транспорт у DNS-запиту?", a: "UDP", wrong: ["TCP", "ICMP", "ARP"], why: "Звичайний запит — UDP/53; TCP використовується для довгих відповідей і зонних передач." },
  { q: "До якого номера йдуть «добре відомі» порти?", a: "1023", wrong: ["255", "4095", "49151"], why: "0–1023 — well-known, 1024–49151 — зареєстровані, далі динамічні." },
  { q: "З якого номера починаються динамічні (ефемерні) порти?", a: "49152", wrong: ["1024", "8000", "32768"], why: "49152–65535 за рекомендацією IANA." },
  { q: "Скільки всього портів у TCP?", a: "65536", wrong: ["1024", "32768", "4096"], why: "Поле порту 16-бітне: від 0 до 65535." },
);

Quiz.run({ questions, kind: "ports", title: "Порти і протоколи" });
