/*
  Порты и протоколы.

  Спрашиваем в обе стороны: номер по названию и название по номеру. Неверные
  варианты — соседние по смыслу службы (SSH/Telnet, HTTP/HTTPS), потому что
  путают именно их.
*/
NL.mount("Порты и протоколы");

const P = [
  ["FTP (данные)", 20, "TCP", "Канал данных FTP. Управляющий — 21."],
  ["FTP (управление)", 21, "TCP", "Команды FTP идут на 21, данные — на 20."],
  ["SSH", 22, "TCP", "Защищённая консоль. Telnet — 23, но он открытым текстом."],
  ["Telnet", 23, "TCP", "Открытый текст, в проде не используется."],
  ["SMTP", 25, "TCP", "Отправка почты. Приём — POP3 (110) или IMAP (143)."],
  ["DNS", 53, "UDP/TCP", "Запросы по UDP, зонные передачи по TCP."],
  ["DHCP (сервер)", 67, "UDP", "Сервер слушает 67, клиент отвечает с 68."],
  ["TFTP", 69, "UDP", "Простой обмен файлами без авторизации, часто для образов IOS."],
  ["HTTP", 80, "TCP", "Открытый веб. Зашифрованный — 443."],
  ["POP3", 110, "TCP", "Забирает почту с удалением с сервера."],
  ["NTP", 123, "UDP", "Синхронизация времени."],
  ["IMAP", 143, "TCP", "Почта остаётся на сервере, в отличие от POP3."],
  ["SNMP", 161, "UDP", "Опрос устройств. Ловушки приходят на 162."],
  ["LDAP", 389, "TCP", "Каталог пользователей. Защищённый — 636."],
  ["HTTPS", 443, "TCP", "HTTP поверх TLS."],
  ["SMB", 445, "TCP", "Общие папки Windows."],
  ["RDP", 3389, "TCP", "Удалённый рабочий стол Windows."],
  ["MySQL", 3306, "TCP", "База данных MySQL/MariaDB."],
  ["PostgreSQL", 5432, "TCP", "База данных PostgreSQL."],
];

const nums = P.map(p => p[1]);
const names = P.map(p => p[0]);
const otherNums = n => NL.shuffle(nums.filter(x => x !== n)).slice(0, 3).map(String);
const otherNames = s => NL.shuffle(names.filter(x => x !== s)).slice(0, 3);

const questions = [];
for (const [name, port, proto, why] of P) {
  questions.push({ q: "Какой порт у этой службы?", given: name, a: String(port), wrong: otherNums(port), why });
  questions.push({ q: "Какая служба слушает этот порт?", given: String(port), a: name, wrong: otherNames(name), why });
}

questions.push(
  { q: "Какой транспорт у DNS-запроса?", a: "UDP", wrong: ["TCP", "ICMP", "ARP"], why: "Обычный запрос — UDP/53; TCP используется для длинных ответов и зонных передач." },
  { q: "До какого номера идут «хорошо известные» порты?", a: "1023", wrong: ["255", "4095", "49151"], why: "0–1023 — well-known, 1024–49151 — зарегистрированные, дальше динамические." },
  { q: "С какого номера начинаются динамические (эфемерные) порты?", a: "49152", wrong: ["1024", "8000", "32768"], why: "49152–65535 по рекомендации IANA." },
  { q: "Сколько всего портов у TCP?", a: "65536", wrong: ["1024", "32768", "4096"], why: "Поле порта 16-битное: от 0 до 65535." },
);

Quiz.run({ questions, kind: "ports", title: "Порты и протоколы" });
